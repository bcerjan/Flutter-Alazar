import 'package:alazar_control/repository/models/all_experiments_enum.dart';
import 'package:alazar_control/repository/models/experiment.dart';
import 'package:alazar_control/repository/repositories/experiment_repository.dart';
import 'package:dart_mappable/dart_mappable.dart';
import 'package:hydrated_bloc/hydrated_bloc.dart';
import 'package:bloc_concurrency/bloc_concurrency.dart';

part 'experiment_state.dart';
part 'experiment_event.dart';
part 'experiment_bloc.mapper.dart'; // autogenerated

class ExperimentBloc extends HydratedBloc<ExperimentEvent, ExperimentState> {
  ExperimentBloc({required this.repository}) : super(const ExperimentState()) {
    on<ExperimentUpdateEvent>(_mapExperimentUpdateEventToState);
    on<ExperimentStartStopEvent>(_mapExperimentStartStopEventToState,
        transformer: sequential()); // process all events in order
    on<ExperimentDetectBoards>(_mapExperimentDetectBoardsEventToState);
  }

  final ExperimentRepository repository;

  @override
  ExperimentState fromJson(Map<String, dynamic> json) =>
      ExperimentStateMapper.fromMap(json);

  @override
  Map<String, dynamic> toJson(ExperimentState state) => state.toMap();

  void _mapExperimentUpdateEventToState(
      ExperimentUpdateEvent event, Emitter<ExperimentState> emit) {
    final bool newType =
        state.experiment.runtimeType != event.experiment.runtimeType;
    // Also copy boards if they exist already (as this is the same machine):
    final settings = state.experiment.settings.copyWith();
    ExperimentState newState = state.copyWith(
        experiment: event.experiment.copyWith(settings: settings));

    if (newType) {
      newState = newState.store(state.experiment);
      Experiment? cachedExp =
          state.retrieve(AllExperimentsEnum.fromModel(event.experiment));
      if (cachedExp != null) {
        emit(newState.copyWith(experiment: cachedExp));
        return;
      }
    }

    emit(newState);
  }

  void _mapExperimentStartStopEventToState(
      ExperimentStartStopEvent event, Emitter<ExperimentState> emit) {}

  void _mapExperimentDetectBoardsEventToState(
      ExperimentDetectBoards event, Emitter<ExperimentState> emit) async {
    try {
      final boards = await repository.detectBoards();
      if (boards.isEmpty) {
        emit(state.copyWith(
            status: ExperimentStatus.error,
            errorText: 'No boards detected on system'));
        return;
      }
      final newExp = state.experiment.copyWith.settings(boards: boards);
      emit(state.copyWith(experiment: newExp));
    } catch (e, stacktrace) {
      print(stacktrace);
      emit(state.copyWith(
          status: ExperimentStatus.error, errorText: e.toString()));
    }
  }
}
